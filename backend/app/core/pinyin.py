def pinyin_initials(text: str) -> str:
    """Return the pinyin first letters of a Chinese string (ASCII passes through).

    Example: pinyin_initials("乳腺癌") -> "rxa".
    """
    out: list = []
    for ch in text:
        if ch.isascii():
            if ch.isalpha():
                out.append(ch.lower())
            continue
        out.append(PINYIN_INITIALS.get(ch, ""))
    return "".join(out)
